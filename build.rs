//! Embeds the shipped catalog in the binary so `estus catalog install` can write
//! it to disk. The layout rules match the ones the Nix package enforces:
//! regular files only, known extensions, no interpreter caches.

use std::{
    env,
    error::Error,
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};

const EXTENSIONS: &[&str] = &["json", "toml", "py", "yml", "yaml"];

fn collect(
    directory: &Path,
    relative: &Path,
    out: &mut Vec<(String, PathBuf)>,
) -> Result<(), Box<dyn Error>> {
    let mut entries = fs::read_dir(directory)?.collect::<Result<Vec<_>, _>>()?;
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let name = entry
            .file_name()
            .into_string()
            .map_err(|_| "catalog file name is not UTF-8")?;
        // Editor and OS droppings (.DS_Store, backups) never belong to the catalog.
        if name.starts_with('.') || name.ends_with('~') {
            continue;
        }
        let path = entry.path();
        let relative = relative.join(&name);
        let kind = entry.file_type()?;
        if kind.is_symlink() {
            return Err(format!("symlink in catalog: {}", path.display()).into());
        }
        if kind.is_dir() {
            if name != "__pycache__" {
                collect(&path, &relative, out)?;
            }
        } else if kind.is_file() {
            if name.ends_with(".pyc") || name.ends_with(".pyo") {
                continue;
            }
            let allowed = path
                .extension()
                .and_then(|extension| extension.to_str())
                .is_some_and(|extension| EXTENSIONS.contains(&extension));
            if !allowed {
                return Err(format!("unexpected catalog asset: {}", path.display()).into());
            }
            let relative = relative
                .to_str()
                .ok_or("catalog path is not UTF-8")?
                .replace('\\', "/");
            out.push((relative, path));
        } else {
            return Err(format!("unexpected catalog entry: {}", path.display()).into());
        }
    }
    Ok(())
}

fn main() -> Result<(), Box<dyn Error>> {
    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").ok_or("CARGO_MANIFEST_DIR")?);
    let root = manifest_dir.join("catalog");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=catalog");

    let mut files = Vec::new();
    collect(&root, Path::new(""), &mut files)?;
    if !files.iter().any(|(relative, _)| relative == "catalog.json") {
        return Err("catalog/catalog.json is missing".into());
    }
    files.sort();

    let mut source = String::from(
        "// @generated by build.rs; the catalog as it was when this binary was built.\n\
         pub(crate) static FILES: &[(&str, &[u8])] = &[\n",
    );
    for (relative, path) in &files {
        let path = path.to_str().ok_or("catalog path is not UTF-8")?;
        writeln!(source, "    ({relative:?}, include_bytes!({path:?})),")?;
    }
    source.push_str("];\n");

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").ok_or("OUT_DIR")?);
    fs::write(out_dir.join("embedded_catalog.rs"), source)?;
    Ok(())
}
